import type { PlacedFurniture, RoomState, Rotation4 } from '../types/room.js';

function makeFurni(
  roomId: string,
  items: Array<{
    catalogItemId: string;
    x: number;
    y: number;
    z?: number;
    rotation?: Rotation4;
    state?: Record<string, unknown>;
  }>
): PlacedFurniture[] {
  return items.map((item, idx) => ({
    id: `${roomId}-f-${idx + 1}`,
    roomId,
    catalogItemId: item.catalogItemId,
    ownerId: 'system',
    x: item.x,
    y: item.y,
    z: item.z ?? 0,
    rotation: item.rotation ?? 0,
    state: item.state ?? {},
  }));
}

